export const translations = { tr, en };
export type Language = keyof typeof translations;

export function label(labels: Record<string, string>, code: string) {
  return Object.hasOwn(labels, code) ? labels[code] : undefined;
}

export function slackHttpStatus(code: string) {
  return /^slack_http_(\d{3})$/.exec(code)?.[1];
}
